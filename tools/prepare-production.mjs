const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const readText = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const count = (hay, needle) => hay.split(needle).length - 1;

/* A transform returns { after } for the review state, { finished: true } for
   the already-applied state, or throws for anything else. */
function applyPairs(rel, text, pairs) {
  /* A replacement shorter than four characters (an empty string, a lone
     quote) is not a usable finished-state marker; only the absence of its
     old text is checked for those. */
  const isMarker = (n) => n.length >= 4;
  const allOld = pairs.every(([o]) => count(text, o) === 1);
  const allNew = pairs.every(([o, n]) => count(text, o) === 0 && (!isMarker(n) || count(text, n) === 1));
  if (allNew) { return { finished: true }; }
  if (!allOld) {
    const bad = pairs.filter(([o]) => count(text, o) !== 1).map(([o]) => o.slice(0, 60));
    throw new Error(rel + ': unexpected state, expected exactly one occurrence of: ' + JSON.stringify(bad));
  }
  let out = text;
  /* function form so "$" sequences in the replacement are never interpreted */
  for (const [o, n] of pairs) { out = out.replace(o, () => n); }
  return { after: out };
}
function transformPage(rel, text) {
  const pairs = [[FOOTER_SUFFIX, '']];
  if (!UTILITY_NOINDEX.has(rel)) { pairs.push([REVIEW_META, INDEX_META]); }
  else if (count(text, REVIEW_META) !== 1) { throw new Error(rel + ': utility page must keep exactly one review noindex meta'); }
  const r = applyPairs(rel, text, pairs);
  if (r.finished && UTILITY_NOINDEX.has(rel) && count(text, REVIEW_META) !== 1) { throw new Error(rel + ': finished state lost its noindex'); }
  if (r.finished && count(text, FOOTER_SUFFIX) !== 0) { throw new Error(rel + ': preview suffix present in finished state'); }
  return r;
}
function transformExact(rel, text, oldText, newText) {
  if (text === newText) { return { finished: true }; }
  if (text !== oldText) { throw new Error(rel + ': content is neither the expected review version nor the finished production version'); }
  return { after: newText };
}

function plan() {
  const items = [];
  for (const rel of AUTHORED_PAGES) { items.push({ rel, ...transformPage(rel, readText(rel)) }); }
  items.push({ rel: 'privacy/index.html', ...applyPairs('privacy/index.html', readText('privacy/index.html'), PRIVACY) });
  items.push({ rel: 'terms/index.html', ...applyPairs('terms/index.html', readText('terms/index.html'), TERMS) });
  items.push({ rel: 'robots.txt', ...transformExact('robots.txt', readText('robots.txt'), OLD_ROBOTS, NEW_ROBOTS) });
  items.push({ rel: '.vercelignore', ...transformExact('.vercelignore', readText('.vercelignore'), OLD_VERCELIGNORE, NEW_VERCELIGNORE) });
  items.push({ rel: 'tests/test_site.py', ...applyPairs('tests/test_site.py', readText('tests/test_site.py'), TEST_SITE) });
  /* privacy and terms appear twice (page transform + pairs); merge by path */
  const merged = new Map();
  for (const it of items) {
    const prev = merged.get(it.rel);
    if (!prev) { merged.set(it.rel, { rel: it.rel, finished: !!it.finished, after: it.after }); continue; }
    if (it.finished && prev.finished) { continue; }
    const base = prev.after !== undefined ? prev.after : readText(it.rel);
    if (it.rel === 'privacy/index.html' || it.rel === 'terms/index.html') {
      const pairs = it.rel === 'privacy/index.html' ? PRIVACY : TERMS;
      const r = applyPairs(it.rel, base, pairs);
      merged.set(it.rel, { rel: it.rel, finished: false, after: r.finished ? base : r.after });
    }
  }
  const list = [...merged.values()];
  const finished = list.filter((i) => i.finished).length;
  if (finished !== 0 && finished !== list.length) {
    throw new Error('Mixed state: ' + finished + ' of ' + list.length + ' files already finished. Refusing; restore the review tree or the finished tree before rerunning.');
  }
  return { list, allFinished: finished === list.length };
}

function hashUntouched(modifiedSet) {
  const out = {};
  for (const rel of [...PUBLIC_FILES, 'vercel.json', 'justin/card.html', 'justin/justin-portrait.webp', 'justin/justin-whalen.vcf', 'assets/media/manifest.json']) {
    if (modifiedSet.has(rel)) { continue; }
    const p = path.join(ROOT, rel);
    if (fs.existsSync(p)) { out[rel] = sha(fs.readFileSync(p)); }
  }
  return out;
}

function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check' && args[0] !== '--apply')) {
    console.error('REFUSED: usage is node tools/prepare-production.mjs [--check | --apply]');
    process.exit(2);
  }
  const apply = args[0] === '--apply';
  const mp4 = path.join(ROOT, LOCKED_MP4.rel);
  if (!fs.existsSync(mp4) || sha(fs.readFileSync(mp4)) !== LOCKED_MP4.sha256) {
    console.error('REFUSED: approved video hash mismatch or file missing: ' + LOCKED_MP4.rel);
    process.exit(2);
  }
  const { list, allFinished } = plan();
  const modified = new Set(list.map((i) => i.rel));
  const untouchedBefore = hashUntouched(modified);
  const report = { mode: apply ? 'apply' : 'check', root: ROOT, lockedMedia: { ...LOCKED_MP4, verified: true }, allFinished, files: [] };
  for (const it of list) {
    const before = fs.readFileSync(path.join(ROOT, it.rel));
    const entry = { path: it.rel, status: it.finished ? 'already-applied' : (apply ? 'applied' : 'proposed'), sha256Before: sha(before) };
    if (!it.finished) {
      entry.sha256After = sha(Buffer.from(it.after, 'utf8'));
      if (apply) { fs.writeFileSync(path.join(ROOT, it.rel), it.after, 'utf8'); }
    }
    report.files.push(entry);
  }
  const untouchedAfter = hashUntouched(modified);
  const drift = Object.keys(untouchedBefore).filter((k) => untouchedBefore[k] !== untouchedAfter[k]);
  report.untouchedPublicFiles = Object.keys(untouchedBefore).length;
  report.untouchedDrift = drift;
  if (sha(fs.readFileSync(mp4)) !== LOCKED_MP4.sha256) { report.lockedMedia.verified = false; }
  if (drift.length || !report.lockedMedia.verified) {
    console.error('ERROR: unrelated bytes changed: ' + JSON.stringify(drift));
    console.log(JSON.stringify(report, null, 2));
    process.exit(1);
  }
  console.log(JSON.stringify(report, null, 2));
  console.log(allFinished ? 'Finished production state verified; nothing written.' : (apply ? 'Release-only edits applied. Nothing deleted, nothing deployed.' : 'Dry run only; nothing written. Rerun with --apply to write.'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) { main(); }
